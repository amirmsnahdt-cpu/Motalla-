#!/usr/bin/env python3
"""Build app.js and styles.css from src/.

The app ships as ONE app.js and ONE styles.css (same as before: no change to
index.html, the server, the service worker or the githack updater). For editing,
the code lives in small files under src/js and src/css; this script joins them
in filename order, byte-for-byte, so the shipped files behave exactly the same.

Usage:
  python3 tools/build.py          # rebuild app.js + styles.css
  python3 tools/build.py --check  # fail if app.js/styles.css are out of date

Never edit app.js or styles.css directly: they carry a hash of their body, and
the build refuses to overwrite a file whose body was changed by hand.
"""
import hashlib, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = [('app.js', 'src/js', '*.js'), ('styles.css', 'src/css', '*.css')]
HDR = re.compile(r'^/\* GENERATED by tools/build\.py from (\S+) — do not edit this file; edit the parts there\. sha:([0-9a-f]{12}) \*/\n')


def sha(s):
    return hashlib.sha256(s.encode('utf-8')).hexdigest()[:12]


def build(check):
    bad = False
    for out, folder, pat in TARGETS:
        parts = sorted((ROOT / folder).glob(pat))
        if not parts:
            sys.exit(f'no source files in {folder}')
        body = ''.join(p.read_text(encoding='utf-8') for p in parts)
        new = f'/* GENERATED by tools/build.py from {folder}/ — do not edit this file; edit the parts there. sha:{sha(body)} */\n' + body
        dst = ROOT / out
        old = dst.read_text(encoding='utf-8') if dst.exists() else ''
        m = HDR.match(old)
        if m and sha(old[m.end():]) != m.group(2):
            sys.exit(f'{out} was edited by hand (its hash does not match). Move that change into {folder}/ first, then build.')
        if old == new:
            continue
        if check:
            print(f'{out} is out of date: run python3 tools/build.py')
            bad = True
        else:
            dst.write_text(new, encoding='utf-8')
            print(f'{out} <- {len(parts)} files from {folder}/')
    if bad:
        sys.exit(1)


if __name__ == '__main__':
    build('--check' in sys.argv)
